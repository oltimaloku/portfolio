"""
Traces Vancouver's skyline from reference images into src/components/drawing/vancouver-data.ts.

    python3 scripts/trace-skyline.py PHOTO.png MOUNTAINS.png CITY.png

PHOTO      the full photograph
MOUNTAINS  the same image with everything but the mountains transparent
CITY       the same image with only the downtown towers kept; any background
           pixels must differ from PHOTO (a baked-in checkerboard works)

The ridge is the top edge of MOUNTAINS. The towers come from the pixels where
CITY still matches PHOTO: their upper envelope is cut into plateaus, and each
plateau becomes a tower. Heights are exaggerated a little so the skyline reads
at small sizes. Requires Pillow.
"""

import json
import sys

from PIL import Image, ImageChops, ImageFilter

OUT = "src/components/drawing/vancouver-data.ts"
SPAN = 1080  # panorama units Vancouver occupies
BASE = 400  # waterline
STEP = 4  # sample every n pixels


def top_edge(mask, y_from=0, y_to=None, run=1):
    w, h = mask.size
    px = mask.load()
    y_to = y_to or h
    out = []
    for x in range(0, w, STEP):
        found, n = None, 0
        for y in range(y_from, y_to):
            n = n + 1 if px[x, y] > 128 else 0
            if n >= run:
                found = y - run + 1
                break
        out.append((x, found))
    return out


def main(photo_path, mountains_path, city_path):
    photo = Image.open(photo_path).convert("RGB")
    w = photo.width
    sx = SPAN / w

    ridge = [(x, y) for x, y in top_edge(Image.open(mountains_path).split()[-1]) if y and 8 < x < w - 14]
    smooth = [(ridge[i][0], sum(y for _, y in ridge[max(0, i - 2) : i + 3]) / len(ridge[max(0, i - 2) : i + 3])) for i in range(len(ridge))]
    ridge_pts = [(round(x * sx, 1), round(BASE - (130 + (340 - y) * 1.35), 1)) for x, y in smooth[::3]]

    city = Image.open(city_path).convert("RGB").resize(photo.size)
    same = ImageChops.difference(photo, city).convert("L").point(lambda v: 255 if v < 18 else 0).filter(ImageFilter.MedianFilter(7))
    tops = [(x, y) for x, y in top_edge(same, 400, 1000, run=14) if y is not None and x >= 530]
    envelope = [(tops[i][0], min(y for _, y in tops[max(0, i - 3) : i + 4])) for i in range(len(tops))]

    def height(y):
        return 24 + max(0, (940 - y) / 500) ** 1.5 * 125

    towers, start = [], 0
    for i in range(1, len(envelope) + 1):
        if i == len(envelope) or abs(envelope[i][1] - envelope[start][1]) > 10:
            seg = envelope[start:i]
            if len(seg) >= 3:
                x0, x1 = seg[0][0] * sx, seg[-1][0] * sx
                towers.append((round(x0, 1), round(x1 - x0 + STEP * sx, 1), round(height(min(y for _, y in seg)), 1)))
            start = i

    with open(OUT, "w") as f:
        f.write(
            "// Generated by tracing a reference photo of Vancouver from the water (see scripts/trace-skyline.py).\n"
            "// RIDGE: the North Shore mountains as [x, y] in panorama units. TOWERS: downtown as [x, width, height].\n"
            f"export const RIDGE: [number, number][] = {json.dumps(ridge_pts)};\n"
            f"export const TOWERS: [number, number, number][] = {json.dumps(towers)};\n"
        )
    print(f"{len(ridge_pts)} ridge points, {len(towers)} towers -> {OUT}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
